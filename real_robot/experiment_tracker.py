import argparse
import csv
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

PROJECT = Path(__file__).resolve().parents[1]
TRACKER = PROJECT / 'experiments/real_robot_tracker'
SPLITS = ('train', 'validation', 'test')
REVIEW_FIELDS = ['attempt_id', 'decision', 'speed_bin', 'target_id', 'notes']
RUN_FIELDS = ['run_id', 'model', 'variant', 'dataset_version', 'dataset_path', 'checkpoint',
              'seed', 'status', 'git_commit', 'config_path', 'updates', 'learning_rate',
              'train_loss', 'validation_action_mse', 'started_utc', 'finished_utc', 'notes']
TRIAL_FIELDS = ['trial_id', 'run_id', 'task_id', 'condition', 'evaluation_set', 'outcome',
                'duration_s', 'failure_reason', 'video_path', 'recorded_utc', 'notes']


def read_json(path):
    return json.loads(Path(path).read_text())


def read_lines(path):
    return [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_csv(path, fields, rows):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix('.tmp')
    with temporary.open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction='ignore')
        writer.writeheader()
        writer.writerows(rows)
    temporary.replace(path)


def input_csv(path, fields):
    if not path.exists():
        write_csv(path, fields, [])
    with path.open(newline='') as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != fields:
            raise ValueError(f'Unexpected columns in {path}')
        return list(reader)


def unique(rows, key):
    result = {}
    for row in rows:
        value = row[key].strip()
        if not value or value in result:
            raise ValueError(f'Missing or duplicate {key}: {value!r}')
        result[value] = row
    return result


def tex(value):
    escapes = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
               '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}',
               '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}
    return ''.join(escapes.get(c, c) for c in str(value))


def table(caption, label, headers, rows):
    columns = 'l' + 'r' * (len(headers)-1)
    body = [' & '.join(map(tex, row)) + r' \\' for row in rows]
    return '\n'.join([r'% Generated by real_robot.experiment_tracker. Do not edit.',
        r'\begin{table}[t]', r'\centering', r'\scriptsize',
        r'\setlength{\tabcolsep}{3pt}', '\\caption{' + tex(caption) + '}',
        '\\label{' + label + '}', '\\begin{tabular}{' + columns + '}', r'\toprule',
        ' & '.join(map(tex, headers)) + r' \\', r'\midrule', *body,
        r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def wilson(successes, trials):
    """Nominal 95% binomial Wilson interval; not variation across training seeds."""
    if trials == 0:
        return None, None
    z = 1.959963984540054
    p = successes/trials
    denominator = 1 + z*z/trials
    center = (p + z*z/(2*trials))/denominator
    margin = z*math.sqrt(p*(1-p)/trials + z*z/(4*trials*trials))/denominator
    return max(0., center-margin), min(1., center+margin)


def scan_collections(collections, plan, reviews):
    tasks = {task['id'] for task in plan['tasks']}
    attempts, sessions, warnings = [], [], []
    for manifest_path in sorted(Path(collections).glob('*/recording/manifest.json')):
        root = manifest_path.parent
        manifest = read_json(manifest_path)
        if manifest.get('schema') != 'dom_dynamic_capture_v1' or manifest.get('mode') != 'execute':
            continue
        task, split = manifest['task_id'], manifest['split']
        if task not in tasks or split not in SPLITS:
            raise ValueError(f'Unrecognized task/split: {manifest_path}')
        summary_path = root/'summary.json'
        summary = read_json(summary_path) if summary_path.exists() else {}
        exports = {}
        for sources in sorted(root.parent.glob('dom*/meta/sources.jsonl')):
            report_path = sources.parent.parent/'export_report.json'
            hashes_path = sources.parent/'raw_hashes.json'
            if not report_path.exists() or not read_json(report_path).get('complete') or not hashes_path.exists():
                continue
            hashes = read_json(hashes_path)
            for row in read_lines(sources):
                source = Path(row['source_episode']).resolve()
                if source.parent != (root/'episodes').resolve() or row.get('split') != split:
                    continue
                if hashes.get(str(source)) != digest(source) or hashes.get(str(manifest_path.resolve())) != digest(manifest_path):
                    warnings.append(f'Changed raw source excluded from export counts: {source}')
                    continue
                exports.setdefault(str(source), str(sources.parent.parent.resolve()))
        count = dict(attempts=0, operator_successes=0, failed=0, incomplete=0, exported=0, included=0)
        for episode_path in sorted((root/'episodes').glob('*.json')):
            episode = read_json(episode_path)
            if episode['task_id'] != task or episode['split'] != split:
                raise ValueError(f'Episode/session mismatch: {episode_path}')
            identity = hashlib.sha256((digest(manifest_path)+digest(episode_path)).encode()).hexdigest()[:24]
            review = reviews.get(identity, {})
            decision = review.get('decision') or 'pending'
            if decision not in ('pending', 'include', 'exclude', 'pilot'):
                raise ValueError(f'Invalid review decision: {identity}')
            speed = review.get('speed_bin', '')
            if speed and speed not in plan['speed_bins']:
                raise ValueError(f'Invalid speed bin: {identity}')
            outcome = episode.get('outcome') or 'open'
            exported = outcome == 'success' and str(episode_path.resolve()) in exports
            if decision == 'include' and (not exported or not speed):
                raise ValueError(f'Include requires completed DOM export and reviewed speed bin: {identity}')
            row = dict(attempt_id=identity, session=root.parent.name, task_id=task, split=split,
                       outcome=outcome, exported=int(exported), included=int(decision=='include'),
                       decision=decision, speed_bin=speed, target_id=review.get('target_id',''),
                       reason=episode.get('reason') or '',
                       duration_s=(episode.get('end_monotonic_s')-episode['start_monotonic_s'])
                           if episode.get('end_monotonic_s') is not None else None,
                       raw_episode=str(episode_path.resolve()),
                       dataset_path=exports.get(str(episode_path.resolve()), ''),
                       notes=review.get('notes',''))
            attempts.append(row)
            count['attempts'] += 1
            count['operator_successes'] += outcome=='success'
            count['failed'] += outcome=='failed'
            count['incomplete'] += outcome in ('incomplete','open')
            count['exported'] += exported
            count['included'] += row['included']
        sessions.append(dict(session=root.parent.name, created_utc=manifest.get('created_utc',''),
                             task_id=task, split=split, **count,
                             error=summary.get('error') or '',
                             cleanup_errors='; '.join(summary.get('cleanup_errors', [])),
                             raw_path=str(root.resolve())))
    # Multiple DOM exports or copied raw sessions must not inflate counts.
    deduplicated = {}
    for row in attempts:
        if row['attempt_id'] in deduplicated:
            warnings.append(f'Duplicate raw attempt excluded: {row["raw_episode"]}')
        else:
            deduplicated[row['attempt_id']] = row
    return list(deduplicated.values()), sessions, warnings


def evaluation_summary(trials, runs, plan):
    unique(trials, 'trial_id')
    tasks = {task['id'] for task in plan['tasks']}
    conditions = {row['id'] for row in plan['evaluation']['conditions']}
    groups = {}
    for row in trials:
        if row['run_id'] not in runs or row['task_id'] not in tasks or row['condition'] not in conditions:
            raise ValueError(f'Unknown run, task or condition: {row["trial_id"]}')
        if row['evaluation_set'] not in ('development','test'):
            raise ValueError(f'Missing evaluation set: {row["trial_id"]}')
        if row['outcome'] not in ('pending','success','failure','takeover','timeout','aborted'):
            raise ValueError(f'Invalid evaluation outcome: {row["trial_id"]}')
        if row['outcome'] == 'pending':
            continue
        key = row['run_id'], row['task_id'], row['condition'], row['evaluation_set']
        group = groups.setdefault(key, dict(run_id=key[0], task_id=key[1], condition=key[2],
            evaluation_set=key[3], successes=0, trials=0))
        group['successes'] += row['outcome']=='success'
        group['trials'] += 1
    for group in groups.values():
        group['success_rate'] = group['successes']/group['trials']
        group['ci_low'], group['ci_high'] = wilson(group['successes'], group['trials'])
    return list(groups.values())


def refresh(collections=PROJECT/'scratch/real_robot/collections', tracker=TRACKER,
            tables=PROJECT/'paper/tables/generated', plan_path=PROJECT/'real_robot/collection_plan.json'):
    tracker, tables = Path(tracker), Path(tables)
    tracker.mkdir(parents=True, exist_ok=True)
    tables.mkdir(parents=True, exist_ok=True)
    plan = read_json(plan_path)
    reviews = unique(input_csv(tracker/'reviews.csv', REVIEW_FIELDS), 'attempt_id')
    runs_list = input_csv(tracker/'training_runs.csv', RUN_FIELDS)
    runs = unique(runs_list, 'run_id')
    trials = input_csv(tracker/'evaluation_trials.csv', TRIAL_FIELDS)
    attempts, sessions, warnings = scan_collections(collections, plan, reviews)
    orphan = set(reviews)-{row['attempt_id'] for row in attempts}
    if orphan:
        warnings.append(f'{len(orphan)} review records have no raw source in this scan; preserved outside totals')
    results = evaluation_summary(trials, runs, plan)
    progress = []
    for task in plan['tasks']:
        for split in SPLITS:
            matching = [row for row in attempts if row['task_id']==task['id'] and row['split']==split]
            target = plan['split_blocks_per_task'][split]*sum(s['slots_per_block'] for s in plan['speed_bins'].values())
            included = sum(row['included'] for row in matching)
            progress.append(dict(task_id=task['id'],split=split,target=target,
                exported=sum(row['exported'] for row in matching),included=included,
                remaining=max(0,target-included),operator_successes=sum(row['outcome']=='success' for row in matching)))
    snapshot = dict(generated_utc=datetime.now(timezone.utc).isoformat(),protocol=plan['protocol_version'],
        progress=progress,attempts=attempts,sessions=sessions,runs=runs_list,trials=trials,
        evaluation=results,warnings=warnings,plan=plan)
    for name, rows, fields in [('collection_progress',progress,list(progress[0])),
        ('attempts',attempts,['attempt_id','session','task_id','split','outcome','exported','included','decision','speed_bin','target_id','reason','duration_s','raw_episode','dataset_path','notes']),
        ('sessions',sessions,['session','created_utc','task_id','split','attempts','operator_successes','failed','incomplete','exported','included','error','cleanup_errors','raw_path']),
        ('evaluation_summary',results,['run_id','task_id','condition','evaluation_set','successes','trials','success_rate','ci_low','ci_high'])]:
        write_csv(tracker/(name+'.csv'),fields,rows)
    (tracker/'snapshot.json').write_text(json.dumps(snapshot,indent=2,allow_nan=False)+'\n')
    dataset_rows, actual_rows = [], []
    for task in plan['tasks']:
        rows = [row for row in progress if row['task_id']==task['id']]
        dataset_rows.append([task['id'].replace('_',' '),*[row['target'] for row in rows],sum(row['target'] for row in rows)])
        actual_rows.append([task['id'].replace('_',' '),*[row['included'] for row in rows],sum(row['exported'] for row in rows)])
    dataset_rows.append(['Total',*[sum(row['target'] for row in progress if row['split']==s) for s in SPLITS],sum(row['target'] for row in progress)])
    (tables/'real_dataset_plan.tex').write_text(table('Planned real demonstration collection. Counts are targets, not collected results.',
        'tab:real_dataset_plan',['Object','Train','Val.','Test','Total'],dataset_rows))
    (tables/'real_dataset_summary.tex').write_text(table('Current real demonstrations. Split columns count reviewed study inclusions; exported counts aligned DOM episodes before study review.',
        'tab:real_dataset_summary',['Object','Train','Val.','Test','Exported'],actual_rows))
    result_rows = [[row['run_id'],row['task_id'].replace('_',' '),row['condition'].replace('_',' '),
        f"{row['successes']}/{row['trials']}",f"{100*row['success_rate']:.1f}",
        f"[{100*row['ci_low']:.1f}, {100*row['ci_high']:.1f}]"] for row in results if row['evaluation_set']=='test']
    # Wide table for per-run results; pending outcomes are never represented as 0%.
    content = table('Autonomous held-out robot evaluation. Success rate and nominal 95 percent Wilson binomial intervals are percentages; intervals do not measure training-seed variation.',
        'tab:real_robot_results',['Run','Object','Condition','Successes','Rate','95% CI'],
        result_rows or [['Pending','--','--','--','--','--']])
    (tables/'real_robot_results.tex').write_text(content.replace('{table}', '{table*}'))
    return snapshot


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--collections',type=Path,default=PROJECT/'scratch/real_robot/collections')
    parser.add_argument('--tracker',type=Path,default=TRACKER)
    parser.add_argument('--tables',type=Path,default=PROJECT/'paper/tables/generated')
    parser.add_argument('--workbook',action='store_true',help='Also rebuild the workbook using the bundled artifact runtime')
    parser.add_argument('--workbook-output',type=Path,default=PROJECT/'outputs/krvla-experiment-tracker')
    args = parser.parse_args(argv)
    snapshot = refresh(args.collections,args.tracker,args.tables)
    print(f"Tracker refreshed: {len(snapshot['attempts'])} attempts; "
          f"{sum(r['exported'] for r in snapshot['progress'])} exported; "
          f"{sum(r['included'] for r in snapshot['progress'])} included. Tables: {args.tables}")
    for warning in snapshot['warnings']:
        print('Review: '+warning)
    if args.workbook:
        runtime = Path(os.environ.get('KRVLA_WORKSPACE_DEPENDENCIES',
            str(Path.home()/'.cache/codex-runtimes/codex-primary-runtime/dependencies')))
        node, modules = runtime/'node/bin/node', runtime/'node/node_modules'
        if not node.is_file() or not modules.is_dir():
            raise RuntimeError('Bundled spreadsheet runtime unavailable; CSV and LaTeX outputs were refreshed')
        with tempfile.TemporaryDirectory(prefix='krvla-tracker-') as staging:
            staging=Path(staging)
            (staging/'node_modules').symlink_to(modules,target_is_directory=True)
            builder=staging/'build.mjs'
            shutil.copyfile(Path(__file__).with_name('build_experiment_workbook.mjs'),builder)
            subprocess.run([str(node),str(builder),str(args.tracker.resolve()),str(args.workbook_output.resolve())],check=True)


if __name__ == '__main__':
    main()
